const LANG_STORAGE_KEY = "patchdl.lang";

function savedLanguage() {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY) || "";
  } catch (_) {
    return "";
  }
}

// browser tag like pt-PT or zh-CN to a key of I18N
function normalizeLanguage(tag) {
  const t = String(tag || "").toLowerCase();
  if (!t) return "";
  if (t === "pt" || t.startsWith("pt-")) return "pt-BR";
  if (t === "zh" || t === "zh-cn" || t === "zh-sg" || t.startsWith("zh-hans")) return "zh-Hans";
  return t.split("-")[0];
}

function detectLanguage() {
  const saved = savedLanguage();
  if (saved && saved !== "auto" && I18N[saved]) return saved;
  const prefs = (navigator.languages && navigator.languages.length)
    ? navigator.languages : [navigator.language];
  for (const tag of prefs) {
    const code = normalizeLanguage(tag);
    if (code && I18N[code]) return code;
  }
  return "en";
}

const CURRENT_LANG = detectLanguage();

// saved choice, even if there's no dictionary for it yet
function languageChoice() {
  return savedLanguage() || "auto";
}

function tHas(key) {
  return Boolean((I18N[CURRENT_LANG] && key in I18N[CURRENT_LANG]) || key in I18N.en);
}

function t(key, vars) {
  const dict = I18N[CURRENT_LANG] || {};
  let s = key in dict ? dict[key] : key in I18N.en ? I18N.en[key] : key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m, name) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m);
  }
  return s;
}

// always English, for the diagnostic report
function tEn(key, vars) {
  let s = key in I18N.en ? I18N.en[key] : key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m, name) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m);
  }
  return s;
}

function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
  document.documentElement.lang = CURRENT_LANG;
}

function setLanguage(code) {
  try {
    if (!code || code === "auto") localStorage.removeItem(LANG_STORAGE_KEY);
    else localStorage.setItem(LANG_STORAGE_KEY, code);
  } catch (_) { /* storage blocked, choice dies with the reload. oh well */ }
  location.reload();
}
